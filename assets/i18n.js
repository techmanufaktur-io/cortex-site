  const SUPPORTED = ["en", "de", "fr", "es", "it", "nl"];
  const STORAGE_KEY = "cortexLang";

  // Englische Basis beim Init aus dem DOM einsammeln → verlustfreies Umschalten.
  const enDict = {};
  document.querySelectorAll("[data-i18n]").forEach(el => {
    enDict[el.getAttribute("data-i18n")] = el.innerHTML;
  });
  document.querySelectorAll("[data-i18n-content]").forEach(el => {
    enDict[el.getAttribute("data-i18n-content")] = el.getAttribute("content");
  });
  I18N.en = enDict;

  function detectLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && SUPPORTED.includes(saved)) return saved;
    } catch (e) { /* Safari private mode etc. */ }
    // navigator.languages spiegelt die Accept-Language-Präferenzen des Browsers.
    const prefs = navigator.languages || [navigator.language || "en"];
    for (const tag of prefs) {
      const base = String(tag).slice(0, 2).toLowerCase();
      if (SUPPORTED.includes(base)) return base;
    }
    return "en";
  }

  function apply(lang) {
    const dict = I18N[lang] || I18N.en;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const value = dict[key] || I18N.en[key];
      if (value !== undefined) {
        if (el.tagName === "TITLE") { document.title = value.replace(/<[^>]+>/g, ""); }
        else { el.innerHTML = value; }
      }
    });
    document.querySelectorAll("[data-i18n-content]").forEach(el => {
      const key = el.getAttribute("data-i18n-content");
      const value = dict[key] || I18N.en[key];
      if (value !== undefined) el.setAttribute("content", value);
    });
    document.documentElement.lang = lang;
    const picker = document.getElementById("langPicker");
    if (picker) picker.value = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
  }

  const picker = document.getElementById("langPicker");
  if (picker) picker.addEventListener("change", () => apply(picker.value));

  apply(detectLang());
